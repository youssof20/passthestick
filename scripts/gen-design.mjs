// Generates design/generated/Tokens.*.xaml and site/css/tokens.css from design/tokens.json
// and fails if any declared color pair misses its WCAG contrast minimum.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const t = JSON.parse(readFileSync(join(root, "design/tokens.json"), "utf8"));

const lin = (c) => { c /= 255; return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4; };
const lum = (hex) => { const n = parseInt(hex.slice(1), 16); return 0.2126 * lin(n >> 16) + 0.7152 * lin((n >> 8) & 255) + 0.0722 * lin(n & 255); };
const ratio = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };

let failed = 0;
for (const theme of ["light", "dark"]) {
  for (const [fg, bg, min] of t.contrast.pairs) {
    const r = ratio(t.color[theme][fg], t.color[theme][bg]);
    if (r < min) { failed++; console.error(`FAIL ${theme}: ${fg} on ${bg} = ${r.toFixed(2)} (need ${min})`); }
  }
}
if (failed) { console.error(`${failed} contrast failure(s)`); process.exit(1); }

const pascal = (s) => s[0].toUpperCase() + s.slice(1);
const kebab = (s) => s.replace(/[A-Z]/g, (m) => "-" + m.toLowerCase());
const fontStack = (f) => `"${f.family}", ${f.fallback}`;
const num = (o) => Object.entries(o).filter(([, v]) => typeof v === "number");

const header = "<!-- Generated by scripts/gen-design.mjs from design/tokens.json. Do not edit. -->";
const open = `<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"
    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"
    xmlns:sys="clr-namespace:System;assembly=mscorlib">`;
const wrap = (body) => `${header}\n${open}\n${body}\n</ResourceDictionary>\n`;
const brushes = (theme) => Object.entries(t.color[theme])
  .map(([k, v]) => `  <SolidColorBrush x:Key="Pts${pascal(k)}Brush" Color="${v}"/>`).join("\n");

const metrics = [
  ...Object.entries(t.space).map(([k, v]) => `  <sys:Double x:Key="PtsSpace${k}">${v}</sys:Double>`),
  ...Object.entries(t.space).flatMap(([k, v]) => [
    `  <Thickness x:Key="PtsSpace${k}Thickness">${v}</Thickness>`,
    `  <Thickness x:Key="PtsSpace${k}Top">0,${v},0,0</Thickness>`,
    `  <Thickness x:Key="PtsSpace${k}Bottom">0,0,0,${v}</Thickness>`,
    `  <Thickness x:Key="PtsSpace${k}Right">0,0,${v},0</Thickness>`,
  ]),
  ...Object.entries(t.radius).map(([k, v]) => `  <CornerRadius x:Key="PtsRadius${pascal(k)}">${v}</CornerRadius>`),
  ...num(t.motion).map(([k, v]) => `  <Duration x:Key="PtsMotion${pascal(k)}">0:0:0.${String(v).padStart(3, "0")}</Duration>`),
  ...Object.entries(t.font).map(([k, f]) => `  <FontFamily x:Key="PtsFont${pascal(k)}">${f.family}, ${f.fallback.split(",")[0]}</FontFamily>`),
  ...Object.entries(t.type).map(([k, s]) => `  <sys:Double x:Key="PtsType${pascal(k)}Size">${s.size}</sys:Double>`),
].join("\n");

mkdirSync(join(root, "design/generated"), { recursive: true });
mkdirSync(join(root, "site/css"), { recursive: true });
writeFileSync(join(root, "design/generated/Tokens.Light.xaml"), wrap(brushes("light")));
writeFileSync(join(root, "design/generated/Tokens.Dark.xaml"), wrap(brushes("dark")));
writeFileSync(join(root, "design/generated/Tokens.Metrics.xaml"), wrap(metrics));

const vars = (theme, pad = "  ") => Object.entries(t.color[theme]).map(([k, v]) => `${pad}--c-${kebab(k)}: ${v};`).join("\n");
const css = `/* Generated by scripts/gen-design.mjs from design/tokens.json. Do not edit. */
:root {
${vars("light")}
  color-scheme: light;
${Object.entries(t.space).map(([k, v]) => `  --space-${k}: ${v / 16}rem;`).join("\n")}
${Object.entries(t.radius).map(([k, v]) => `  --radius-${k}: ${v}px;`).join("\n")}
${num(t.motion).map(([k, v]) => `  --motion-${k}: ${v}ms;`).join("\n")}
  --ease-out: cubic-bezier(${t.motion.easing.out});
  --ease-in-out: cubic-bezier(${t.motion.easing.inOut});
  --font-display: ${fontStack(t.font.display)};
  --font-ui: ${fontStack(t.font.ui)};
  --font-code: ${fontStack(t.font.code)};
${Object.entries(t.type).map(([k, s]) => `  --type-${kebab(k)}-size: ${s.size / 16}rem;\n  --type-${kebab(k)}-leading: ${s.lineHeight};\n  --type-${kebab(k)}-weight: ${s.weight};`).join("\n")}
  --focus-width: ${t.focusRing.width}px;
  --focus-offset: ${t.focusRing.offset}px;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${vars("dark", "    ")}
    color-scheme: dark;
  }
}
:root[data-theme="dark"] {
${vars("dark")}
  color-scheme: dark;
}
@media (prefers-reduced-motion: reduce) {
  :root { --motion-instant: 0ms; --motion-quick: 0ms; --motion-handoff: 0ms; }
}
`;
writeFileSync(join(root, "site/css/tokens.css"), css);
console.log("tokens generated; all contrast pairs pass in light and dark");
